#!/usr/bin/env python3
"""Embed firmware files into a kext.

    embed_firmware.py <prefix> <out dir> <firmware files...>

Writes <out>/<file>.z (zlib), <out>/firmware.s (.incbin of each, private to
the kext) and <out>/firmware_table.inc: a `kFirmware[]` array of
FirmwareEntry {name, data, end, decompressed size} for the C++ side.
"""

import os
import sys
import zlib


def main():
    prefix, out, files = sys.argv[1], sys.argv[2], sorted(sys.argv[3:])
    os.makedirs(out, exist_ok=True)
    asm = ["\t.section __TEXT,__const"]
    decls, entries = [], []
    for i, path in enumerate(files):
        name = os.path.basename(path)
        with open(path, "rb") as f:
            raw = f.read()
        blob = os.path.join(out, name + ".z")
        with open(blob, "wb") as f:
            f.write(zlib.compress(raw, 9))
        sym = f"{prefix}_fw_{i}"
        asm += [
            "\t.p2align 4",
            f"\t.private_extern _{sym}",
            f"_{sym}:",
            f'\t.incbin "{os.path.abspath(blob)}"',
            f"\t.private_extern _{sym}_end",
            f"_{sym}_end:",
        ]
        decls.append(f'extern "C" const unsigned char {sym}[], {sym}_end[];')
        entries.append(f'    {{"{name}", {sym}, {sym}_end, {len(raw)}u}},')
    with open(os.path.join(out, "firmware.s"), "w") as f:
        f.write("\n".join(asm) + "\n")
    with open(os.path.join(out, "firmware_table.inc"), "w") as f:
        f.write("// Generated by scripts/embed_firmware.py. Do not edit.\n")
        f.write("\n".join(decls) + "\n\n")
        f.write("static const FirmwareEntry kFirmware[] = {\n")
        f.write("\n".join(entries) + "\n};\n")


if __name__ == "__main__":
    main()
